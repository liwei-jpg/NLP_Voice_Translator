# Import the core AI classes from the Hugging Face 'transformers' library.
# 'MBartForConditionalGeneration' is the neural network structure (the Brain).
# 'MBart50TokenizerFast' is the dictionary tool that turns human words into machine numbers.
from transformers import MBartForConditionalGeneration, MBart50TokenizerFast

# Print a loading message to the terminal. 
# Since loading a 2.4GB file into memory takes time, this prevents the user (or lecturer) 
# from thinking the program has frozen.
print("⏳ Downloading the mBART model and tokenizer... (This is a 2.4GB file, so it might take a few minutes!)")

# Load the specific model and its associated tokenizer
# Define the exact name of the multilingual translation model created by Facebook. 
# 'many-to-many-mmt' means it can translate back and forth between any of the 50 supported languages.
model_name = "facebook/mbart-large-50-many-to-many-mmt"

# Download and initialize the tokenizer. This creates the lookup table the AI uses 
# to map English and Spanish words to mathematical tokens.
tokenizer = MBart50TokenizerFast.from_pretrained(model_name)

# Download and initialize the actual neural network weights. 
# This loads the core intelligence into your computer's memory.
model = MBartForConditionalGeneration.from_pretrained(model_name)

# Print a success message to let the user know the heavy lifting of loading the model is done.
print("\n✅ Model loaded successfully!")

# 1. Set the source language to English
# mBART is multilingual, so it needs to know what language it is currently reading. 
# We explicitly set the source language code to English ('en_XX').
tokenizer.src_lang = "en_XX"

# Define a test sentence. This acts as our "Baseline Verification" to prove the model 
# works correctly before we try adding our custom LoRA training weights.
english_sentence = "Hello, my name is Lee and I am building an artificial intelligence project."

# Print the input sentence to the terminal for the user to see.
print(f"\n🗣️ English Input: {english_sentence}")

# Print a status update so the user knows the AI is calculating.
print("⚙️ Translating...")

# 2. Convert the text into numbers (tokens) the model can process
# Transform the human-readable text into PyTorch tensors (multi-dimensional arrays of numbers). 
# The AI can only perform math, so it requires inputs to be in this 'pt' (PyTorch) format.
inputs = tokenizer(english_sentence, return_tensors="pt")

# 3. Generate the translation, explicitly forcing the output language to Spanish (es_XX)
# Command the model to predict and generate the translated sentence.
generated_tokens = model.generate(
    # The double asterisk (**) unpacks our dictionary of input numbers so the model can read them properly.
    **inputs,
    # BOS stands for "Beginning Of Sentence". We force the very first token generated by the AI 
    # to be the Spanish language code ('es_XX'). This directs the model's attention to output 
    # the rest of the sentence in Spanish.
    forced_bos_token_id=tokenizer.lang_code_to_id["es_XX"]
)

# 4. Decode the output numbers back into human-readable text
# The model outputs a list of numbers. We use the tokenizer to translate those numbers back into Spanish words. 
# 'skip_special_tokens=True' removes the invisible technical tags (like end-of-sentence markers). 
# We use '[0]' to grab the first translation string from the resulting list.
spanish_output = tokenizer.batch_decode(generated_tokens, skip_special_tokens=True)[0]

# Print the final translated result to the terminal.
print(f"🇪🇸 Spanish Output: {spanish_output}")