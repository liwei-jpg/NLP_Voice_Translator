# Import torch to handle the heavy math (tensor calculations) for the AI model
import torch
# Import standard library for handling mBART's language translation
from transformers import MBartForConditionalGeneration, MBart50TokenizerFast
# Import PEFT to manage your custom adapter weights
from peft import PeftModel
# Import 'evaluate' to automate the complex math behind BLEU, ROUGE, and METEOR scores
import evaluate
# Import 'jiwer' specifically for Word Error Rate (WER) calculation
import jiwer

print("⚙️ Loading Evaluation Metrics...")
# We use Hugging Face's library because it provides standardized implementations 
# of academic metrics, ensuring our results are comparable to other research papers.
bleu = evaluate.load("bleu")
rouge = evaluate.load("rouge")
meteor = evaluate.load("meteor")

print("🧠 Loading mBART Model & LoRA Adapter...")
MODEL_NAME = "facebook/mbart-large-50-many-to-many-mmt"
tokenizer = MBart50TokenizerFast.from_pretrained(MODEL_NAME)
base_model = MBartForConditionalGeneration.from_pretrained(MODEL_NAME)
# Inject your trained LoRA adapter back into the model to test its fine-tuned performance
model = PeftModel.from_pretrained(base_model, "./saved_lora_adapter")

# ---------------------------------------------------------
# 1. EVALUATING TRANSLATION (NMT - Neural Machine Translation)
# ---------------------------------------------------------
print("\n--- TRANSLATION EVALUATION (NMT) ---")
# 'english_sources' serves as our input test set.
# 'spanish_references' is the "Ground Truth"—the perfect human translation.
# In ML, comparing Predictions vs Ground Truth is how we calculate accuracy.
english_sources = [
    "Hello, how are you today?",
    "I need to go to the supermarket.",
    "What is your name?"
]

spanish_references = [
    "Hola, ¿cómo estás hoy?",
    "Necesito ir al supermercado.",
    "¿Cómo te llamas?"
]

# This list will hold the raw translations generated by your AI
model_predictions = []

# Setting standard language codes for mBART
tokenizer.src_lang = "en_XX"
tgt_code = tokenizer.lang_code_to_id["es_XX"]

print("Translating test sentences...")
# Iterate through each input sentence
for text in english_sources:
    # Convert text to numerical tokens
    inputs = tokenizer(text, return_tensors="pt")
    # We use torch.no_grad() because we aren't training, so we don't need to save memory 
    # for gradient backpropagation. This speeds up the inference process.
    with torch.no_grad():
        generated_tokens = model.generate(**inputs, forced_bos_token_id=tgt_code)
    # Decode numbers back to plain text
    translation = tokenizer.batch_decode(generated_tokens, skip_special_tokens=True)[0]
    model_predictions.append(translation)
    print(f"Original: {text} | Translated: {translation}")

# Calculate Scores: The compute() function compares your list of predictions
# against the list of human-verified references.
print("\n📊 Translation Scores:")
bleu_results = bleu.compute(predictions=model_predictions, references=spanish_references)
print(f"BLEU Score: {bleu_results['bleu']:.4f} (Measures exact word precision)")

rouge_results = rouge.compute(predictions=model_predictions, references=spanish_references)
print(f"ROUGE-L Score: {rouge_results['rougeL']:.4f} (Measures sentence structure matching)")

meteor_results = meteor.compute(predictions=model_predictions, references=spanish_references)
print(f"METEOR Score: {meteor_results['meteor']:.4f} (Measures semantic meaning and synonyms)")


# ---------------------------------------------------------
# 2. EVALUATING SPEECH RECOGNITION (ASR)
# ---------------------------------------------------------
print("\n--- SPEECH RECOGNITION EVALUATION (ASR) ---")
# WER is a crucial metric for the "Ears" of your system.
# It counts how many words the AI deleted, inserted, or swapped incorrectly.
actual_spoken_words = "Hola cómo estás hoy"
what_whisper_heard = "Hola como estas hoy" 

# jiwer.wer is a standard function that compares the spoken string to the transcribed string.
wer_score = jiwer.wer(actual_spoken_words, what_whisper_heard)
print(f"Word Error Rate (WER): {wer_score:.4f} (Lower is better)")