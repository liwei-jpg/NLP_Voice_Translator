# Import torch to handle the heavy math (tensor calculations) for the AI model
import torch
# Import standard library for handling mBART's language translation
from transformers import MBartForConditionalGeneration, MBart50TokenizerFast
# Import PEFT to inject your LoRA adapter "skills" into the base model
from peft import PeftModel
# Import Whisper for speech recognition (The "Ears")
import whisper
# Import Microsoft's Edge-TTS for high-quality audio generation (The "Mouth")
import edge_tts
# Import asyncio to download audio files in the background without freezing the app
import asyncio
# Import tempfile to create files in RAM that automatically delete themselves
import tempfile
# Import speech_recognition (sr) to interface with your microphone hardware
import speech_recognition as sr
import os
import pygame  # Used to play the MP3 audio files directly through your speakers

print("⚙️ Booting Autonomous AI Translator...")

# --- SETUP: LOAD MODELS INTO MEMORY ---
print("🎧 Loading Whisper (Ears)...")
# 'base' is a balanced model: good accuracy and very fast performance.
asr_model = whisper.load_model("base")

print("🧠 Loading mBART (Brain)...")
MODEL_NAME = "facebook/mbart-large-50-many-to-many-mmt"
tokenizer = MBart50TokenizerFast.from_pretrained(MODEL_NAME)
base_model = MBartForConditionalGeneration.from_pretrained(MODEL_NAME)
# Inject the custom LoRA weights we trained earlier
model = PeftModel.from_pretrained(base_model, "./saved_lora_adapter")

# Initialize pygame's audio mixer to play the MP3s generated by Edge-TTS
pygame.mixer.init()

# --- HELPER: TEXT TO SPEECH ---
def speak_translation(text, target_language):
    # Select the correct neural voice based on target language (Spanish or English)
    voice_model = "es-ES-AlvaroNeural" if target_language == "es" else "en-US-ChristopherNeural"
    
    # Configure the TTS engine with the text and voice model
    communicate = edge_tts.Communicate(text, voice_model)
    
    # Create a temporary file path to store the generated audio before playing
    temp_file = tempfile.NamedTemporaryFile(delete=False, suffix=".mp3")
    temp_filename = temp_file.name
    temp_file.close()
    
    # Run the async save operation to convert the text to an MP3 file
    asyncio.run(communicate.save(temp_filename))
    
    # Load and play the MP3 through the speaker
    pygame.mixer.music.load(temp_filename)
    pygame.mixer.music.play()
    
    # Keep the script paused until the audio finishes playing (prevents clipping)
    while pygame.mixer.music.get_busy():
        pygame.time.Clock().tick(10)
        
    # Delete the temporary file now that we are done with it (cleans up memory)
    os.remove(temp_filename)

# --- MAIN AUTONOMOUS LOOP ---
def start_autonomous_translator():
    # Initialize the microphone listener
    recognizer = sr.Recognizer()
    
    # 1. pause_threshold: The "wait time" after the user stops talking.
    # It keeps the recording open for 1.5s after audio stops to ensure 
    # the user is actually finished, rather than just taking a breath.
    recognizer.pause_threshold = 1.5
    
    # 2. energy_threshold: The volume sensitivity.
    # Anything below this RMS volume value is ignored as background noise.
    recognizer.energy_threshold = 300 
    
    with sr.Microphone() as source:
        print("\n✅ System Ready. Press Ctrl+C to exit.")
        print("🤫 Profiling background noise for 2 seconds...")
        # This records 2 seconds of the environment to calculate background RMS,
        # helping the energy_threshold automatically adjust to room conditions.
        recognizer.adjust_for_ambient_noise(source, duration=2)
        
        while True:
            print("\n🎙️ Listening... (Speak now!)")
            try:
                # 3. Listen: A "blocking call." The entire program waits here
                # until audio is detected and the pause_threshold is met.
                audio_data = recognizer.listen(source, timeout=None)
                print("⏳ Silence detected. Processing...")
                
                # Save the detected voice to a temporary .wav file for Whisper to read
                with tempfile.NamedTemporaryFile(delete=False, suffix=".wav") as temp_wav:
                    temp_wav.write(audio_data.get_wav_data())
                    temp_wav_path = temp_wav.name
                
                # 4. Transcribe: Pass audio data to Whisper
                transcription = asr_model.transcribe(temp_wav_path)
                detected_text = transcription["text"].strip()
                detected_lang = transcription["language"] # Whisper returns 'en' or 'es'
                
                # Delete the temporary WAV file to free up hard drive space
                os.remove(temp_wav_path)
                
                if not detected_text:
                    continue # Skip to next loop if Whisper heard nothing
                    
                # 5. Dynamic Routing: Set parameters based on detected language
                if detected_lang == "en":
                    print(f"🗣️ Detected English: {detected_text}")
                    src_code, tgt_code, target_lang_simple = "en_XX", "es_XX", "es"
                elif detected_lang == "es":
                    print(f"🗣️ Detected Spanish: {detected_text}")
                    src_code, tgt_code, target_lang_simple = "es_XX", "en_XX", "en"
                else:
                    print(f"⚠️ Unrecognized language detected: {detected_lang}")
                    continue
                
                # 6. Translate: mBART logic
                print("⚙️ Translating...")
                tokenizer.src_lang = src_code # Tells the AI to read English or Spanish
                inputs = tokenizer(detected_text, return_tensors="pt")
                
                with torch.no_grad():
                    # Generate the translation
                    generated_tokens = model.generate(
                        **inputs,
                        forced_bos_token_id=tokenizer.lang_code_to_id[tgt_code]
                    )
                
                # Decode the numbers (tokens) back to human words
                translated_text = tokenizer.batch_decode(generated_tokens, skip_special_tokens=True)[0]
                print(f"➡️ Translation: {translated_text}")
                
                # 7. Speak: Final TTS step
                speak_translation(translated_text, target_lang_simple)
                
            except KeyboardInterrupt:
                # Graceful shutdown if the user presses Ctrl+C
                print("\n🛑 Shutting down system.")
                break
            except Exception as e:
                # Catch errors to prevent the entire program from crashing
                print(f"An error occurred: {e}")

if __name__ == "__main__":
    # Self-install pygame if the user doesn't have it, keeping the codebase portable
    try:
        import pygame
    except ImportError:
        print("Installing pygame for audio playback...")
        os.system("pip install pygame")
        import pygame
        
    start_autonomous_translator()