# Import PyTorch, the core machine learning library that handles mathematical tensor operations on the CPU/GPU.
import torch
# Import the essential classes from Hugging Face's 'transformers' library.
# 'MBartForConditionalGeneration' is the massive base translation model (the Brain).
# 'MBart50TokenizerFast' is the dictionary tool that converts human words into machine-readable numbers.
from transformers import MBartForConditionalGeneration, MBart50TokenizerFast
# Import PeftModel (Parameter-Efficient Fine-Tuning). This is the key component that allows us 
# to load our tiny, custom-trained LoRA weights and 'snap' them onto the massive base model.
from peft import PeftModel

# Print a status message to the terminal.
print("⚙️ Loading the base mBART model... (This is fast since it is already cached)")
# Define the exact name of the foundational Facebook translation model.
MODEL_NAME = "facebook/mbart-large-50-many-to-many-mmt"
# Load the tokenizer. Since we already downloaded it previously, this loads instantly from your local cache.
tokenizer = MBart50TokenizerFast.from_pretrained(MODEL_NAME)
# Load the massive 2.4GB base translation model into memory.
base_model = MBartForConditionalGeneration.from_pretrained(MODEL_NAME)

# Print a status message to let the user know the magic is happening.
print("🧬 Injecting your custom fine-tuned LoRA adapter...")
# This merges your newly trained conversational skills into the base model
# This is the most important step. We take the giant 'base_model' and inject your tiny 5MB 
# LoRA adapter (from the saved folder). This instantly upgrades the base model with your custom conversational skills.
model = PeftModel.from_pretrained(base_model, "./saved_lora_adapter")

# Print a success message.
print("✅ Fine-tuned model is ready for use!")

# Define a custom function that takes an English string and returns a Spanish string.
def translate_english_to_spanish(text):
    # Set language tokens
    # mBART supports 50 languages, so we must explicitly tell the tokenizer that the incoming text is in English.
    tokenizer.src_lang = "en_XX"
    
    # Tokenize input text
    # Convert the human-readable text into PyTorch tensors (numerical arrays) that the AI can do math on.
    inputs = tokenizer(text, return_tensors="pt")
    
    # Generate translation forcing Spanish output code
    # 'torch.no_grad()' tells PyTorch NOT to calculate gradients. Since we are just testing/using the model 
    # and not training it anymore, this saves a massive amount of computer memory and makes generation much faster.
    with torch.no_grad():
        # Command the model to predict the translation.
        # '**inputs' unpacks the numerical arrays we made earlier.
        # 'forced_bos_token_id' forces the very first word the AI generates to be the Spanish language tag, ensuring Spanish output.
        generated_tokens = model.generate(
            **inputs,
            forced_bos_token_id=tokenizer.lang_code_to_id["es_XX"]
        )
    
    # Decode back to readable text
    # Take the output numbers generated by the AI and translate them back into human words.
    # 'skip_special_tokens=True' hides the invisible technical tags (like end-of-sentence markers).
    translation = tokenizer.batch_decode(generated_tokens, skip_special_tokens=True)[0]
    # Send the final translated string back to whoever called this function.
    return translation

# --- TEST THE NEW MODEL ---
# This standard Python line ensures the test code below only runs if you run this specific file directly.
if __name__ == "__main__":
    # Print a header to the terminal for visual organization.
    print("\n--- testing custom fine-tuned translator ---")
    
    # Define a casual, conversational test sentence. This proves your LoRA adapter can handle everyday slang, not just formal text.
    test_sentence = "Hey friend, are we still meeting up for dinner tonight or what?"
    # Display the original sentence to the user.
    print(f"🗣️ English Input: {test_sentence}")
    
    # Print a status update so the user knows the AI is actively "thinking".
    print("⚡ Translating with your custom conversational skills...")
    # Call our custom function from above, passing in the test sentence, and save the answer in the 'result' variable.
    result = translate_english_to_spanish(test_sentence)
    
    # Print the final Spanish translation to the screen.
    print(f"🇪🇸 Conversational Spanish Output: {result}")